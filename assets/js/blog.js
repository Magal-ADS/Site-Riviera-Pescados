function loadArticle() {
    const params = new URLSearchParams(window.location.search);
    const articleId = params.get('id');

    if (articleId && blogData[articleId]) {
        const article = blogData[articleId];

        // Atualiza Título da Página
        document.title = `Riviera Pescados | ${article.title}`;

        // Atualiza Keyword e Título
        const keywordElement = document.querySelector('.article-keyword');
        if (keywordElement) keywordElement.textContent = `Palavra-chave: ${article.keyword}`;
        
        const titleElement = document.querySelector('.article-header h1');
        if (titleElement) titleElement.textContent = article.title;

        // Atualiza Imagem
        const imageElement = document.querySelector('.article-hero-image');
        if (imageElement) {
            imageElement.src = article.image;
            imageElement.alt = article.title;
        }

        // Atualiza Conteúdo
        const contentElement = document.querySelector('.article-text-body');
        if (contentElement) {
            contentElement.innerHTML = article.content;
        }
    }
}

document.addEventListener('DOMContentLoaded', loadArticle);
